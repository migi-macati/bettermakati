import { mkdir, writeFile } from 'node:fs/promises';
import { fetchGoogleNews } from './news-feed.mjs';

const result = await fetchGoogleNews({ limit: 30 });
await mkdir('src/data', { recursive: true });
await writeFile(
  'src/data/newsSnapshot.ts',
  `import type { NewsItem } from './newsTypes';\n\n// Generated by the weekly content workflow. The live /api/news feed remains the primary source.\nexport const newsSnapshot: NewsItem[] = ${JSON.stringify(result.items, null, 2)};\n`
);
console.log(
  `Saved ${result.items.length} Makati news items to src/data/newsSnapshot.ts using ${result.meta.policyVersion}`
);
