import { mkdir, writeFile } from 'node:fs/promises';
import { fetchGoogleNews } from './news-feed.mjs';

const items = await fetchGoogleNews({ limit: 30 });
await mkdir('src/data', { recursive: true });
await writeFile(
  'src/data/newsSnapshot.ts',
  `export type NewsItem = {\n  title: string;\n  link: string;\n  description: string;\n  pubDate: string;\n  source: string;\n  sourceUrl: string;\n};\n\n// Generated by the weekly content workflow. The live /api/news feed remains the primary source.\nexport const newsSnapshot: NewsItem[] = ${JSON.stringify(items, null, 2)};\n`
);
console.log(
  `Saved ${items.length} Makati news items to src/data/newsSnapshot.ts`
);
