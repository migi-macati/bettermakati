import { mkdir, writeFile } from 'node:fs/promises';
import { fetchGoogleNews } from './news-feed.mjs';

const result = await fetchGoogleNews({ limit: 30 });
await mkdir('src/data', { recursive: true });
await mkdir('data', { recursive: true });

await writeFile(
  'src/data/newsSnapshot.ts',
  `import type { NewsItem } from './newsTypes';\n\n// Generated by the news discovery workflow. The live /api/news feed remains the primary public source.\nexport const newsSnapshot: NewsItem[] = ${JSON.stringify(result.items, null, 2)};\n`
);

await writeFile(
  'data/news-discovery-snapshot.json',
  JSON.stringify(
    {
      version: 1,
      generatedAt: result.meta.retrievedAt,
      policyVersion: result.meta.policyVersion,
      sourceHealth: result.meta.sourceHealth,
      items: result.items,
    },
    null,
    2
  ) + '\n'
);

console.log(
  `Saved ${result.items.length} Makati news items and discovery metadata using ${result.meta.policyVersion}`
);
