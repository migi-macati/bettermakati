const geometryTypeFor = (asset: CivicAsset): PlaceGeometry['type'] => {
  if (asset.type === 'transport-route') return 'route';
  if (asset.type === 'park') return 'area';
  if (
    asset.type === 'street-segment' ||
    asset.type === 'sidewalk-segment' ||
    asset.type === 'bike-lane'
  ) {
    return 'segment';
  }
  return 'point';
};

const verificationStatusFor = (asset: CivicAsset): PlaceVerificationStatus => {
  if (asset.status === 'needs-verification') return 'needs-verification';
  if (asset.status === 'mapped' && asset.sourceUrl && asset.coordinateSourceUrl) return 'verified';
  return 'provisional';
};

const placeSourcesFor = (asset: CivicAsset): PlaceSource[] => {
  const sources: PlaceSource[] = [];
  if (asset.sourceUrl && asset.sourceLabel) {
    sources.push({
      id: asset.id + ':identity',
      label: asset.sourceLabel,
      url: asset.sourceUrl,
      kind: 'other',
    });
  }
  if (asset.coordinateSourceUrl && asset.coordinateSourceLabel) {
    sources.push({
      id: asset.id + ':coordinates',
      label: asset.coordinateSourceLabel,
      url: asset.coordinateSourceUrl,
      kind: 'reference-map',
    });
  }
  return sources;
};

const placeAssertionsFor = (asset: CivicAsset): PlaceAssertion[] => {
  const assertions: PlaceAssertion[] = [];
  if (asset.sourceUrl && asset.sourceLabel) {
    assertions.push({
      fieldPaths: ['name'],
      sourceIds: [asset.id + ':identity'],
      evidenceStrength: 'direct',
    });
  }
  if (asset.coordinateSourceUrl && asset.coordinateSourceLabel) {
    assertions.push({
      fieldPaths: ['location.point'],
      sourceIds: [asset.id + ':coordinates'],
      evidenceStrength: 'direct',
    });
  }
  return assertions;
};

/**
 * Shared canonical place records.
 *
 * W3R-2b intentionally derives these records from the existing verified Civic Map seed set so
 * every current ID and page behavior remain stable. The flat civicAssets export stays available
 * as a compatibility view while other site surfaces begin adopting placeRegistry in later steps.
 */
export const placeRegistry: PlaceRegistryRecord[] = civicAssets.map((asset): PlaceRegistryRecord => ({
  id: asset.id,
  name: asset.title,
  summary: asset.subtitle,
  primaryCategory: asset.type,
  aliases: asset.aliases?.map(name => ({
    name,
    kind: 'unclassified' as const,
    note: 'Migrated from the Civic Map alias list without inferring whether the name is current, historical or local.',
  })),
  location: {
    relationToMakati: asset.type === 'transport-route' ? 'route-or-network' : 'in-makati',
    barangays: asset.barangay ? [asset.barangay] : [],
    address: asset.address,
    point: {
      lat: asset.lat,
      lng: asset.lng,
      role: 'representative',
    },
    geometry: {
      type: geometryTypeFor(asset),
      street: asset.street,
      from: asset.from,
      to: asset.to,
      side: asset.side,
    },
  },
  management: {
    responsibilityText: asset.authority,
    bodies: [],
  },
  servicesAtLocation: asset.servicesAtLocation?.map(label => ({ label })),
  access: {
    class: asset.accessClass ?? 'unknown',
  },
  lifecycle: {
    status: 'unknown',
    note: 'Lifecycle is intentionally not inferred from Civic Map mapping status.',
  },
  verification: {
    status: verificationStatusFor(asset),
  },
  provenance: {
    sources: placeSourcesFor(asset),
    assertions: placeAssertionsFor(asset),
  },
  relationships: [],
  tags: [...asset.tags],
}));

export const placeRegistryById = new Map(placeRegistry.map(place => [place.id, place]));
